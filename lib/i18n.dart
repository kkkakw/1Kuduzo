// Язык интерфейса. Русский — в коде, английский — словарь ниже.
// Text из этого файла заменяет стандартный: строка переводится при отрисовке, поэтому
// const Text('…') по-прежнему работает, а смена языка применяется ко всему приложению сразу.
import 'dart:ui' as ui;

import 'package:flutter/material.dart' as mat;
import 'package:flutter/widgets.dart' hide Text;

enum AppLang { system, ru, en }

class L {
  static bool en = false;

  /// Языки, носителям которых понятнее русский интерфейс, чем английский.
  static const _ruLike = {'ru', 'uk', 'be', 'kk', 'ky', 'tg', 'uz', 'hy', 'az', 'tk'};

  /// Применить выбор языка. Возвращает true, если язык поменялся.
  static bool apply(AppLang lang) {
    final sys = ui.PlatformDispatcher.instance.locale.languageCode.toLowerCase();
    final next = switch (lang) {
      AppLang.en => true,
      AppLang.ru => false,
      AppLang.system => !_ruLike.contains(sys),
    };
    final changed = next != en;
    en = next;
    return changed;
  }

  /// Выбор между русским и английским вариантом строки, собранной в коде.
  static String pick(String ru, String en) => L.en ? en : ru;
}

/// Перевод строки интерфейса (русский — как есть).
String tr(String s) {
  if (!L.en || s.isEmpty) return s;
  final hit = _en[s];
  if (hit != null) return hit;
  for (final (re, f) in _patterns) {
    final m = re.firstMatch(s);
    if (m != null) return f(m);
  }
  return s;
}

/// Text с переводом. Подключается вместо стандартного: import 'package:flutter/material.dart' hide Text;
class Text extends StatelessWidget {
  const Text(
    this.data, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  });

  final String data;
  final TextStyle? style;
  final StrutStyle? strutStyle;
  final TextAlign? textAlign;
  final TextDirection? textDirection;
  final Locale? locale;
  final bool? softWrap;
  final TextOverflow? overflow;
  final TextScaler? textScaler;
  final int? maxLines;
  final String? semanticsLabel;
  final TextWidthBasis? textWidthBasis;
  final ui.TextHeightBehavior? textHeightBehavior;
  final Color? selectionColor;

  @override
  Widget build(BuildContext context) => mat.Text(
        tr(data),
        style: style,
        strutStyle: strutStyle,
        textAlign: textAlign,
        textDirection: textDirection,
        locale: locale,
        softWrap: softWrap,
        overflow: overflow,
        textScaler: textScaler,
        maxLines: maxLines,
        semanticsLabel: semanticsLabel,
        textWidthBasis: textWidthBasis,
        textHeightBehavior: textHeightBehavior,
        selectionColor: selectionColor,
      );
}

